function normalizeFaqText(value: string): string {
  return value.toLowerCase().replace(/[\s\p{P}\p{S}]+/gu, '');
}

/** เลือกคำตอบที่เกี่ยวข้องสำหรับคำถามพิมพ์เอง เพื่อให้ AI ได้บริบทหลายมุมที่ตรงหัวข้อ */
export function getRelevantFaqAnswers(question: string, limit = 3): FaqAnswer[] {
  const normalizedQuestion = normalizeFaqText(question);
  if (!normalizedQuestion) return [];

  return Object.entries(FAQ_ANSWERS)
    .map(([faqQuestion, answer]) => {
      const phrases = [faqQuestion, ...(FAQ_MATCH_ALIASES[faqQuestion] ?? [])];
      const score = phrases.reduce((best, phrase) => {
        const normalizedPhrase = normalizeFaqText(phrase);
        if (!normalizedPhrase || !normalizedQuestion.includes(normalizedPhrase)) return best;
        return Math.max(best, normalizedPhrase === normalizedQuestion ? 100 : normalizedPhrase.length >= 8 ? 10 : 5);
      }, 0);
      return { answer, score };
    })
    .filter(item => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(item => item.answer);
}

export function getFaqAnswer(question: string): FaqAnswer | undefined {
  return FAQ_ANSWERS[question.trim()];
}
